// WCAG 2.x contrast maths and the declared-pair evaluation behind
// `npm run check:contrast` (see ../contrast-check.mjs).

export const thresholds = { text: 4.5, 'large-text': 3, boundary: 3, decoration: null };

/** Relative luminance of a `#RRGGBB` colour (WCAG 2.x). */
export function luminance(hex) {
  const m = /^#([0-9a-f]{6})$/i.exec(hex);
  if (!m) throw new Error(`not a #RRGGBB colour: ${hex}`);
  const [r, g, b] = [0, 2, 4].map((i) => {
    const c = Number.parseInt(m[1].slice(i, i + 2), 16) / 255;
    return c <= 0.03928 ? c / 12.92 : ((c + 0.055) / 1.055) ** 2.4;
  });
  return 0.2126 * r + 0.7152 * g + 0.0722 * b;
}

/** Contrast ratio of two colours, 1 to 21. */
export function ratio(a, b) {
  const [hi, lo] = [luminance(a), luminance(b)].sort((x, y) => y - x);
  return (hi + 0.05) / (lo + 0.05);
}

export const round2 = (n) => Math.round(n * 100) / 100;

/** Resolves a role name (for a theme) or a full token path to a hex colour. */
function resolve(tokens, name, theme) {
  const t = tokens[name.includes('.') ? name : `color.theme.${theme}.${name}`];
  if (!t) throw new Error(`unknown colour "${name}" for theme ${theme}`);
  return t.$value.toUpperCase();
}

/**
 * Evaluates the declared pairs against the flat resolved [tokens]
 * (dist/json/tokens.json). Every row carries `ok` (false means the check fails)
 * and `pass` (the pair itself clears its threshold: true, false, or null for an
 * unthresholded decoration). An `assertFail` pair is ok only when `pass` is false;
 * an `expect` ratio must reproduce to 2 decimals.
 */
export function evaluate(tokens, def) {
  const rows = [];
  for (const p of def.pairs) {
    if (!(p.kind in thresholds)) throw new Error(`unknown kind "${p.kind}" for ${p.fg}/${p.bg}`);
    const fg = resolve(tokens, p.fg, p.theme);
    const bg = resolve(tokens, p.bg, p.theme);
    const r = ratio(fg, bg);
    const required = p.min ?? thresholds[p.kind];
    const pass = required === null ? null : r >= required;
    const reasons = [];
    let ok = p.assertFail ? pass === false : pass !== false;
    if (p.assertFail && pass !== false) reasons.push('asserted to fail but passes');
    if (p.expect !== undefined && round2(r) !== p.expect) {
      ok = false;
      reasons.push(`expected ${p.expect.toFixed(2)}:1`);
    }
    rows.push({
      fg, fgName: p.fg, bg, bgName: p.bg, theme: p.theme ?? '-', kind: p.kind, ratio: r, required, pass,
      assertFail: Boolean(p.assertFail), ok, note: p.note ?? '', reason: reasons.join('; '),
    });
  }
  return { rows };
}

const fmt = (n) => n.toFixed(2);
/** Result column: `pass`, `exempt`, `FAIL`, `asserted fail (ok)`. */
export function status(r) {
  if (!r.ok) return 'FAIL';
  if (r.assertFail) return 'asserted fail (ok)';
  return r.pass === null ? 'exempt' : 'pass';
}

const reqText = (r) => (r.required === null ? 'n/a' : `${fmt(r.required)}:1`);

/** Plain-text table for the terminal; failures name the pair and the measured ratio. */
export function renderText({ rows }) {
  const head = ['pair (fg / bg)', 'theme', 'kind', 'ratio', 'required', 'result'];
  const body = rows.map((r) => [
    `${r.fgName} / ${r.bgName}`, r.theme, r.kind, `${fmt(r.ratio)}:1`, reqText(r),
    status(r) + (r.reason ? ` (${r.reason})` : ''),
  ]);
  const widths = head.map((h, i) => Math.max(h.length, ...body.map((b) => b[i].length)));
  const line = (cells) => cells.map((c, i) => c.padEnd(widths[i])).join('  ');
  const out = [line(head), line(widths.map((w) => '-'.repeat(w))), ...body.map(line), ''];
  for (const r of rows.filter((x) => !x.ok)) {
    out.push(`FAIL: ${r.fgName} on ${r.bgName} (${r.theme}, ${r.kind}) measured ${fmt(r.ratio)}:1, required ${reqText(r)}${r.reason ? `; ${r.reason}` : ''}`);
  }
  return `${out.join('\n')}\n`;
}

/** Markdown for docs/contrast.md. */
export function renderMarkdown({ rows }) {
  const cell = (s) => (s ? `\`${s}\`` : '');
  const out = [
    '<!-- Generated by `npm run check:contrast`. Do not edit. -->',
    '',
    '# Contrast',
    '',
    'WCAG 2.x contrast of the declared pairs (`tokens/contrast-pairs.json`). Text needs 4.5:1, large text',
    'and UI boundaries need 3:1, decoration has no threshold and is listed so the exemption stays visible.',
    'A row marked "asserted fail (ok)" is a rejected option that must keep failing.',
    '',
    '| Foreground | Background | Theme | Kind | Foreground colour | Background colour | Ratio | Required | Result | Note |',
    '| --- | --- | --- | --- | --- | --- | --- | --- | --- | --- |',
    ...rows.map((r) => `| \`${r.fgName}\` | \`${r.bgName}\` | ${r.theme} | ${r.kind} | ${cell(r.fg)} | ${cell(r.bg)} | ${fmt(r.ratio)}:1 | ${reqText(r)} | ${status(r)}${r.reason ? ` (${r.reason})` : ''} | ${r.note} |`),
    '',
  ];
  return out.join('\n');
}

/** True when nothing failed. */
export const allPass = ({ rows }) => rows.every((r) => r.ok);
